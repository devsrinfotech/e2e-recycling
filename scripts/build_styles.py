"""Conservatively prune class/ID selectors absent from the static site, then bundle.

Preserves pseudo states, tag/attribute selectors, nested conditions and keyframes.
Source stylesheets remain editable; no CSS parser dependency is needed at runtime.
"""
from pathlib import Path
from html.parser import HTMLParser
import re

ROOT=Path(__file__).resolve().parent.parent

class Tokens(HTMLParser):
    def __init__(self):
        super().__init__()
        self.classes={'active','collapsed','show','is-open','header-sticky','is-expanded','is-current'}
        self.ids={'primary-navigation'}
    def handle_starttag(self,tag,attrs):
        a=dict(attrs)
        self.classes.update(a.get('class','').split())
        if a.get('id'): self.ids.add(a['id'])

def blocks(css):
    start=0; depth=0; quote=None; escaped=False; opening=None
    for i,char in enumerate(css):
        if escaped: escaped=False; continue
        if char=='\\': escaped=True; continue
        if quote:
            if char==quote: quote=None
            continue
        if char in ('"',"'"): quote=char; continue
        if char=='{':
            if depth==0: opening=i
            depth+=1
        elif char=='}':
            depth-=1
            if depth==0:
                yield css[start:opening].strip(),css[opening+1:i]
                start=i+1
    if depth or quote: raise ValueError('Unbalanced CSS source')

def prune(css,tokens):
    result=[]
    for selector,body in blocks(css):
        if selector.startswith(('@media','@supports','@layer')):
            inner=prune(body,tokens)
            if inner: result.append(selector+'{'+inner+'}')
        elif selector.startswith('@'):
            result.append(selector+'{'+body.strip()+'}')
        else:
            keep=[]
            for item in selector.split(','):
                # Negative conditions do not require that a class occur in HTML.
                positive=re.sub(r':not\([^)]*\)','',item)
                classes=set(re.findall(r'\.([a-zA-Z_][\w-]*)',positive))
                ids=set(re.findall(r'#([a-zA-Z_][\w-]*)',positive))
                if classes<=tokens.classes and ids<=tokens.ids: keep.append(item.strip())
            if keep: result.append(','.join(keep)+'{'+body.strip()+'}')
    return ''.join(result)

def build():
    tokens=Tokens()
    for path in ROOT.glob('*.html'): tokens.feed(path.read_text(encoding='utf-8'))
    sources=['bootstrap.min.css','font-awesome.min.css','dark.css','growth.css']
    output=[]; before=0
    for name in sources:
        css=ROOT.joinpath('assets/css',name).read_text(encoding='utf-8')
        before+=len(css.encode('utf-8'))
        css=re.sub(r'/\*.*?\*/','',css,flags=re.S)
        output.append(prune(css,tokens))
    # Preserve source licence attribution in the generated deliverable.
    bundled='/*! Bootstrap MIT; Font Awesome CSS MIT / font SIL OFL; Turing theme by tempload. Source licences retained in assets/css. Generated by scripts/build_styles.py. */\n'+''.join(output)
    bundled=re.sub(r'\s+',' ',bundled)
    bundled=re.sub(r'\s*([{};])\s*',r'\1',bundled)
    ROOT.joinpath('assets/css/site.min.css').write_text(bundled+'\n',encoding='utf-8')
    for path in ROOT.glob('*.html'):
        text=path.read_text(encoding='utf-8')
        if 'class="growth-page"' in text: continue
        text=re.sub(r'<link\b[^>]*href="(?:\./)?assets/css/(?:bootstrap\.min|font-awesome\.min|dark|growth|site\.min)\.css"[^>]*>','',text)
        text=text.replace('</head>','<link rel="stylesheet" href="assets/css/site.min.css">\n</head>')
        path.write_text('\n'.join(line.rstrip() for line in text.splitlines())+'\n',encoding='utf-8')
    print(f'Legacy stylesheet bundle: {before:,} -> {len(bundled.encode("utf-8")):,} bytes.')

if __name__=='__main__': build()
